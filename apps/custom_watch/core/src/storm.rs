    #[test]
    fn points_older_than_the_window_leave_the_trend() {
        // A steep fall, then flat air for a whole window: the fall must age out
        // rather than keeping a storm on the page for the rest of the day.
        let mut t = fast();
        let end = walk(
            &mut t,
            0,
            2_400,
            |_| 300.0,
            |i| 1_013.0 - 6.0 * f64::from(i) as f32 / 1_800.0,
        );
        assert_eq!(t.view(end).trend, StormTrend::Storm);
        let end = walk(&mut t, end, 2_400, |_| 300.0, |_| 1_005.0);
        let v = t.view(end);
        assert!(
            v.delta_hpa.unwrap().abs() < 0.5,
            "the aged-out fall still moves the slope: {v:?}"
        );
    }

    #[test]
    fn a_signal_void_mid_window_keeps_the_trend_it_can_still_measure() {
        // Both ends of the window were corroborated; only the middle was lost.
        // The slope over what remains is a real measurement of a real interval,
        // so the void costs resolution, not the verdict.
        let mut t = fast();
        let end = walk(
            &mut t,
            0,
            600,
            |_| 300.0,
            |i| 1_013.0 - 6.0 * f64::from(i) as f32 / 1_800.0,
        );
        for i in 0..600u32 {
            t.on_sample(station_pa(300.0, 1_011.0), None, end + i);
        }
        let end = walk(
            &mut t,
            end + 600,
            600,
            |_| 300.0,
            |i| 1_009.0 - 6.0 * f64::from(i) as f32 / 1_800.0,
        );
        let v = t.view(end);
        assert_eq!(v.trend, StormTrend::Storm, "{v:?}");
        assert!(v.span_s >= t.min_span_s);
    }

