    #[test]
    fn a_thin_bucket_is_dropped_rather_than_banked() {
        // One reduction is ~1.8 hPa of altitude noise on its own. A bucket that
        // caught fewer than three readings must not become a point the slope is
        // fitted through.
        let mut t = StormTracker::with_cadence(10, 120);
        // Two readings per 10 s bucket, for two minutes.
        for i in 0..12u32 {
            for k in 0..2u32 {
                let at = i * 10 + k;
                t.on_sample(station_pa(300.0, 1_013.0), Some(300.0), at);
            }
        }
        assert_eq!(t.len, 0, "thin buckets banked");
        assert_eq!(t.view(120).trend, StormTrend::Building);
    }

    #[test]
    fn the_storm_latch_holds_through_a_partial_recovery() {
        // Open at the threshold, then let the fall shallow to just inside it:
        // the word must not flicker off and on while the front is still there.
        let mut t = fast();
        let mut v = StormView {
            trend: StormTrend::Steady,
            sea_level_hpa: None,
            delta_hpa: Some(-4.5),
            span_s: 600,
        };
        t.on_view(&v);
        assert_eq!(t.classify(-4.5), StormTrend::Storm);
        // Recovered past the opening threshold but not past the release: held.
        v.delta_hpa = Some(-3.0);
        t.on_view(&v);
        assert_eq!(t.classify(-3.0), StormTrend::Storm);
        // Past the release: cleared, and it stays cleared at the same value.
        v.delta_hpa = Some(-1.9);
        t.on_view(&v);
        assert_eq!(t.classify(-1.9), StormTrend::Falling);
        assert_eq!(t.classify(-3.0), StormTrend::Falling);
    }

    #[test]
    fn a_lost_reference_does_not_clear_a_latched_storm() {
        // The front is still out there; the watch merely stopped being able to
        // see it. Clearing on silence would retract a warning on no evidence.
        let mut t = fast();
        t.on_view(&StormView {
            trend: StormTrend::Storm,
            sea_level_hpa: None,
            delta_hpa: Some(-5.0),
            span_s: 900,
        });
        assert!(t.latched);
        t.on_view(&StormView {
            trend: StormTrend::NoReference,
            sea_level_hpa: None,
            delta_hpa: None,
            span_s: 0,
        });
        assert!(t.latched, "silence cleared the latch");
    }

    #[test]
    fn the_threshold_setter_refuses_what_it_cannot_believe() {
        let mut t = fast();
        for bad in [
            0.0,
            STORM_THRESHOLD_MIN_HPA - 0.01,
            STORM_THRESHOLD_MAX_HPA + 0.01,
            -4.0,
            f32::NAN,
            f32::INFINITY,
        ] {
            t.set_fall_threshold_hpa(bad);
            assert_eq!(t.fall_threshold_hpa(), STORM_FALL_HPA, "{bad} was taken");
        }
        t.set_fall_threshold_hpa(2.0);
        assert_eq!(t.fall_threshold_hpa(), 2.0);
        // ...and the release scales with it.
        assert_eq!(t.classify(-1.5), StormTrend::Falling);
        t.on_view(&StormView {
            trend: StormTrend::Steady,
            sea_level_hpa: None,
            delta_hpa: Some(-2.0),
            span_s: 900,
        });
        assert_eq!(t.classify(-1.5), StormTrend::Storm);
    }

    #[test]
    fn the_window_can_never_outrun_the_ring() {
        // A caller asking for more window than STORM_HISTORY holds would get a
        // trend fitted over a silently truncated history.
        let t = StormTracker::with_cadence(300, 1_000_000);
        assert_eq!(t.window_s, 300 * (STORM_HISTORY as u32 - 1));
        assert_eq!(t.window_s, STORM_WINDOW_S);
        // ...and a window under two buckets cannot hold the two points a slope
        // needs.
        let t = StormTracker::with_cadence(300, 10);
        assert_eq!(t.window_s, 600);
    }

