    #[test]
    fn a_reference_that_goes_stale_withdraws_the_trend() {
        // A canyon, a canopy, a receiver in backup mode: the trend was real and
        // then the corroboration stopped. The watch reports that it stopped.
        let mut t = fast();
        let end = walk(
            &mut t,
            0,
            2_400,
            |_| 300.0,
            |i| 1_013.0 - 6.0 * f64::from(i) as f32 / 1_800.0,
        );
        assert_eq!(t.view(end).trend, StormTrend::Storm);
        // `walk` leaves the clock one tick past its last sample, so the budget
        // is measured from there.
        let last = end - 1;
        assert_eq!(
            t.view(last + STORM_REFERENCE_MAX_AGE_S).trend,
            StormTrend::Storm,
            "inside the budget the trend still stands"
        );
        assert_eq!(
            t.view(last + STORM_REFERENCE_MAX_AGE_S + 1).trend,
            StormTrend::NoReference
        );
    }

    #[test]
    fn a_short_history_is_building_not_a_verdict() {
        // A tendency extrapolated from a fifth of its window multiplies its own
        // residual fivefold; the honest answer is that it is not ready.
        let mut t = fast();
        let end = walk(
            &mut t,
            0,
            300,
            |_| 300.0,
            |i| 1_013.0 - 6.0 * f64::from(i) as f32 / 1_800.0,
        );
        let v = t.view(end);
        assert_eq!(v.trend, StormTrend::Building);
        assert_eq!(v.delta_hpa, None);
        // The absolute pressure IS known from the first reading, and the page
        // shows it — only its tendency is withheld.
        assert!(v.sea_level_hpa.is_some());
    }

