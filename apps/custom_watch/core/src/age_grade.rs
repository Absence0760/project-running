//! Age grading — score a race performance against the world-standard time for
//! the runner's exact age and sex, so a 68-year-old's marathon and a
//! 24-year-old's are comparable on one 0-100% scale.
//!
//! A parity port of web `runs/age_grade.ts` (twin of `age_grade.dart`), with
//! the embedded USATF-MLDR 2025 factor tables from `age_grade_tables.ts`.
//!
//!   percent = open_standard_sec / (duration_sec * age_factor) * 100
//!
//! `open_standard_sec` is the open-class (world-standard) time for the distance
//! and sex; `age_factor` (<= 1) is the single-year age factor. A runner who
//! matches the age standard scores 100%; world-record-grade efforts exceed it.
//!
//! The `nonbinary`/unset-sex path the web helper rejects at runtime is
//! unrepresentable here — [`AgeGradeSex`] has only the two binary variants age
//! grading is defined for — so [`age_grade_for_run`] takes `Option<AgeGradeSex>`
//! and yields `None` for `None`.
//!
//! Pure logic, no peripherals, no allocator. `libm` for float math off-test.

// Factor values that coincidentally equal math constants (0.7071, 0.4343,
// 0.7854, ...) are age-grade data, not approximations of those constants.
#![allow(clippy::approx_constant)]

use core::fmt::Write as _;

/// Youngest age the factor tables cover.
pub const AGE_GRADE_AGE_MIN: i32 = 5;
/// Oldest age the factor tables cover.
pub const AGE_GRADE_AGE_MAX: i32 = 99;

/// Max relative gap between a run's distance and a standard distance for the
/// run to be age-graded against it. Age grading is defined only at the standard
/// distances; GPS over-reads a certified course by ~1%, so a small tolerance
/// catches real races without grading a 5.4 km jog as a 5 km.
pub const AGE_GRADE_DISTANCE_TOLERANCE: f64 = 0.02;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum AgeGradeSex {
    Male,
    Female,
}

/// One standard distance: certified length, the open-class standard time per
/// sex, and the age-factor arrays (ages 5..=99, indexed by `age - 5`).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AgeGradeDistance {
    /// Source-file key, e.g. `5k`, `hm`, `42k`.
    pub key: &'static str,
    /// Human label, e.g. `5 km`, `Half marathon`, `Marathon`.
    pub label: &'static str,
    /// Certified distance in metres.
    pub distance_m: f64,
    /// Open-class (world-standard) male time in seconds.
    pub open_standard_male_sec: f64,
    /// Open-class (world-standard) female time in seconds.
    pub open_standard_female_sec: f64,
    /// Male age factors for ages 5..=99, indexed by `age - 5`.
    pub factors_male: &'static [f64; 95],
    /// Female age factors for ages 5..=99, indexed by `age - 5`.
    pub factors_female: &'static [f64; 95],
}

/// The result of grading a performance.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AgeGradeResult {
    /// Age grade as a percentage, e.g. 72.4. Not capped — WR-grade efforts
    /// exceed 100.
    pub percent: f64,
    /// Matched standard distance the grade is computed against.
    pub distance: &'static AgeGradeDistance,
    /// Whole-years age used for the factor lookup.
    pub age: i32,
    /// Age factor (<= 1) applied.
    pub factor: f64,
}

