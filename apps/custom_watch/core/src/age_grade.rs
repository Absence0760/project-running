/// The standard distance closest to `distance_m`, if within
/// [`AGE_GRADE_DISTANCE_TOLERANCE`]; otherwise `None` (not a recognised race
/// distance → no age grade).
pub fn match_standard_distance(distance_m: f64) -> Option<&'static AgeGradeDistance> {
    if distance_m.is_nan() || distance_m <= 0.0 {
        return None;
    }
    let mut best: Option<&'static AgeGradeDistance> = None;
    let mut best_rel = f64::INFINITY;
    for d in &AGE_GRADE_DISTANCES {
        let rel = libm::fabs(distance_m - d.distance_m) / d.distance_m;
        if rel < best_rel {
            best_rel = rel;
            best = Some(d);
        }
    }
    match best {
        Some(b) if best_rel <= AGE_GRADE_DISTANCE_TOLERANCE => Some(b),
        _ => None,
    }
}

struct Ymd {
    y: i32,
    m: i32,
    d: i32,
}

/// Whole-years age on a given date — "age on race day", which is what age
/// grading uses (not age today). Both args are ISO strings; only the leading
/// `YYYY-MM-DD` is read, so timezones never shift the result. `None` if either
/// is unparseable or the date precedes birth.
pub fn age_on_date(dob_iso: &str, on_iso: &str) -> Option<i32> {
    let dob = parse_ymd(dob_iso)?;
    let on = parse_ymd(on_iso)?;
    let mut age = on.y - dob.y;
    if on.m < dob.m || (on.m == dob.m && on.d < dob.d) {
        age -= 1;
    }
    if (0..200).contains(&age) {
        Some(age)
    } else {
        None
    }
}

fn parse_ymd(iso: &str) -> Option<Ymd> {
    if iso.len() < 10 {
        return None;
    }
    let bytes = iso.as_bytes();
    if bytes[4] != b'-' || bytes[7] != b'-' {
        return None;
    }
    let y: i32 = iso.get(0..4)?.parse().ok()?;
    let m: i32 = iso.get(5..7)?.parse().ok()?;
    let d: i32 = iso.get(8..10)?.parse().ok()?;
    if !(1..=12).contains(&m) || !(1..=31).contains(&d) {
        return None;
    }
    Some(Ymd { y, m, d })
}

/// Age grade for a known distance + duration + whole-years age + sex, or `None`
/// when it can't be computed: distance not standard, age outside the table
/// (5..=99), or a non-positive duration.
pub fn compute_age_grade(
    distance_m: f64,
    duration_sec: f64,
    age: i32,
    sex: AgeGradeSex,
) -> Option<AgeGradeResult> {
    if duration_sec.is_nan() || duration_sec <= 0.0 {
        return None;
    }
    if !(AGE_GRADE_AGE_MIN..=AGE_GRADE_AGE_MAX).contains(&age) {
        return None;
    }
    let distance = match_standard_distance(distance_m)?;
    let idx = (age - AGE_GRADE_AGE_MIN) as usize;
    let (factor, open_standard) = match sex {
        AgeGradeSex::Male => (distance.factors_male[idx], distance.open_standard_male_sec),
        AgeGradeSex::Female => (
            distance.factors_female[idx],
            distance.open_standard_female_sec,
        ),
    };
    if factor <= 0.0 || open_standard <= 0.0 {
        return None;
    }
    let percent = (open_standard / (duration_sec * factor)) * 100.0;
    Some(AgeGradeResult {
        percent,
        distance,
        age,
        factor,
    })
}

/// Convenience over [`compute_age_grade`] that derives age from the runner's
/// DOB and the run's start date. `sex` is `None` for unset / non-binary, which
/// yields `None` (age grading has no standard without a binary sex reference).
pub fn age_grade_for_run(
    distance_m: f64,
    duration_sec: f64,
    dob_iso: Option<&str>,
    run_start_iso: Option<&str>,
    sex: Option<AgeGradeSex>,
) -> Option<AgeGradeResult> {
    let dob = dob_iso?;
    let run_start = run_start_iso?;
    let sex = sex?;
    let age = age_on_date(dob, run_start)?;
    compute_age_grade(distance_m, duration_sec, age, sex)
}

/// Display string, e.g. `72.4%`. One decimal is the masters convention.
pub fn format_age_grade_percent(percent: f64) -> heapless::String<8> {
    let mut s = heapless::String::new();
    let _ = write!(s, "{percent:.1}%");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn match_standard_distance_exact_distances_map_to_their_standard() {
        assert_eq!(match_standard_distance(5000.0).unwrap().key, "5k");
        assert_eq!(match_standard_distance(10000.0).unwrap().key, "10k");
        assert_eq!(match_standard_distance(42195.0).unwrap().key, "42k");
        assert_eq!(match_standard_distance(8000.0).unwrap().key, "8k");
    }

    #[test]
    fn match_standard_distance_gps_over_read_within_tolerance_still_matches() {
        assert_eq!(match_standard_distance(5050.0).unwrap().key, "5k");
        assert_eq!(match_standard_distance(21300.0).unwrap().key, "hm");
    }

    #[test]
    fn match_standard_distance_outside_tolerance_returns_none() {
        assert!(match_standard_distance(5400.0).is_none());
        assert!(match_standard_distance(7000.0).is_none());
        assert!(match_standard_distance(0.0).is_none());
        assert!(match_standard_distance(-100.0).is_none());
    }

    #[test]
    fn match_standard_distance_marathon_over_read_maps_to_the_marathon() {
        assert_eq!(match_standard_distance(42400.0).unwrap().key, "42k");
    }

    #[test]
    fn age_on_date_subtracts_a_year_before_the_birthday() {
        assert_eq!(age_on_date("1980-07-15", "2026-06-04T09:00:00Z"), Some(45));
        assert_eq!(age_on_date("1980-07-15", "2026-08-01T09:00:00Z"), Some(46));
        assert_eq!(age_on_date("1980-07-15", "2026-07-15T09:00:00Z"), Some(46));
    }

    #[test]
    fn age_on_date_malformed_input_returns_none() {
        assert_eq!(age_on_date("not-a-date", "2026-06-04"), None);
        assert_eq!(age_on_date("1980-07-15", "nope"), None);
        assert_eq!(age_on_date("1980/07/15", "2026-06-04"), None);
    }

    #[test]
    fn compute_age_grade_peak_age_at_the_open_standard_scores_100() {
        let r = compute_age_grade(5000.0, 769.0, 25, AgeGradeSex::Male).unwrap();
        assert_eq!(r.distance.key, "5k");
        assert_eq!(r.factor, 1.0);
        assert!((r.percent - 100.0).abs() < 1e-9);
    }

    #[test]
    fn compute_age_grade_double_the_standard_time_halves_the_percentage() {
        let r = compute_age_grade(5000.0, 1538.0, 25, AgeGradeSex::Male).unwrap();
        assert!((r.percent - 50.0).abs() < 1e-9);
    }

    #[test]
    fn compute_age_grade_masters_male_10k_matches_the_hand_computed_grade() {
        let r = compute_age_grade(10000.0, 2400.0, 60, AgeGradeSex::Male).unwrap();
        assert_eq!(r.factor, 0.8136);
        assert!((r.percent - 81.121).abs() < 0.01);
    }

    #[test]
    fn compute_age_grade_masters_female_5k_matches_the_hand_computed_grade() {
        let r = compute_age_grade(5000.0, 1200.0, 35, AgeGradeSex::Female).unwrap();
        assert_eq!(r.factor, 0.9793);
        assert!((r.percent - 70.969).abs() < 0.01);
    }

    #[test]
    fn compute_age_grade_returns_none_outside_its_domain() {
        // The web `sex: 'nonbinary'` null-case is unrepresentable — AgeGradeSex
        // has only the two binary variants — so that assertion is dropped here.
        assert!(compute_age_grade(5400.0, 1200.0, 40, AgeGradeSex::Male).is_none());
        assert!(compute_age_grade(5000.0, 1200.0, 4, AgeGradeSex::Male).is_none());
        assert!(compute_age_grade(5000.0, 1200.0, 100, AgeGradeSex::Male).is_none());
        assert!(compute_age_grade(5000.0, 0.0, 40, AgeGradeSex::Male).is_none());
    }

    #[test]
    fn age_grade_for_run_end_to_end_null_when_sex_unknown() {
        let r = age_grade_for_run(
            5000.0,
            769.0,
            Some("2000-01-01"),
            Some("2026-06-04T09:00:00Z"),
            Some(AgeGradeSex::Male),
        )
        .unwrap();
        assert!((r.percent - 100.0).abs() < 1e-9);
        assert_eq!(format_age_grade_percent(r.percent).as_str(), "100.0%");
        assert!(
            age_grade_for_run(5000.0, 769.0, Some("2000-01-01"), Some("2026-06-04"), None)
                .is_none()
        );
        assert!(age_grade_for_run(
            5000.0,
            769.0,
            None,
            Some("2026-06-04"),
            Some(AgeGradeSex::Male)
        )
        .is_none());
        assert!(AGE_GRADE_DISTANCE_TOLERANCE > 0.0);
    }
}
